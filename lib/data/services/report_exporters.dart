/// PDF statement — the format landlords hand to their auditor.
class PdfReportExporter implements ReportExporter {
  const PdfReportExporter();

  @override
  ExportFormat get format => ExportFormat.PDF;

  @override
  Future<Uint8List> build(ReportBundle bundle, {String? propertyName}) async {
    final fonts = await PdfFontSet.resolve();
    final document = pw.Document(
      title: 'RentLedger Report',
      author: 'RentLedger',
    );

    final rows = bundle.transactions;
    final byType = <TransactionType, double>{};
    for (final txn in rows) {
      byType.update(txn.type, (value) => value + txn.amount, ifAbsent: () => txn.amount);
    }

    final byProperty = <String, double>{};
    for (final txn in rows) {
      byProperty.update(
        txn.propertyId,
        (value) => value + (txn.isIncome ? txn.amount : -txn.amount),
        ifAbsent: () => txn.isIncome ? txn.amount : -txn.amount,
      );
    }

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(28, 28, 28, 22),
        theme: pw.ThemeData.withFont(base: fonts.regular, bold: fonts.bold),
        footer: (context) => PdfBlocks.footer(
          fonts: fonts,
          note: 'Generated by RentLedger on '
              '${Formatters.dateTime(bundle.generatedAt)}',
          context: context,
        ),
        build: (context) => <pw.Widget>[
          PdfBlocks.header(
            fonts: fonts,
            title: 'Rental Income & Expense Report',
            subtitle: PdfBlocks.describeFilter(bundle, 'All properties'),
            trailing: 'Generated ${Formatters.date(bundle.generatedAt)}',
          ),
          PdfBlocks.detailPanel(
            fonts: fonts,
            title: 'Period summary',
            rows: <(String, String)>[
              ('Rent collected', fonts.money(bundle.totalRent)),
              ('Maintenance collected', fonts.money(bundle.totalMaintenance)),
              ('Electricity collected', fonts.money(bundle.totalEb)),
              ('Water collected', fonts.money(bundle.totalWater)),
              ('Other income', fonts.money(_otherIncome(bundle))),
              ('Total income', fonts.money(bundle.totalIncome)),
              ('Total expenses', fonts.money(bundle.totalExpenses)),
              ('Net operating income', fonts.money(bundle.netIncome)),
              ('Advance received', fonts.money(bundle.totalAdvanceReceived)),
              ('Advance refunded', fonts.money(bundle.totalAdvanceRefund)),
              ('Units billed (EB)', Formatters.units(bundle.totalUnitsBilled)),
              ('Entries', '${bundle.transactions.length}'),
            ],
          ),
          pw.SizedBox(height: 16),
          if (byProperty.length > 1) ...[
            pw.Text('Property-wise net', style: fonts.heading),
            pw.SizedBox(height: 6),
            PdfBlocks.lineItemTable(
              fonts: fonts,
              items: byProperty.entries
                  .map(
                    (entry) => (
                      bundle.propertyNameFor(entry.key),
                      fonts.moneyShort(entry.value),
                    ),
                  )
                  .toList(growable: false),
            ),
            pw.SizedBox(height: 16),
          ],
          pw.Text('Transaction ledger', style: fonts.heading),
          pw.SizedBox(height: 6),
          PdfBlocks.transactionTable(fonts: fonts, bundle: bundle),
          pw.SizedBox(height: 18),
          pw.Text(
            'This statement is generated from your recorded entries. '
            'Please retain the original receipts for audit purposes.',
            style: fonts.bodyMuted,
          ),
        ],
      ),
    );

    return document.save();
  }

  static double _otherIncome(ReportBundle bundle) {
    final known = bundle.totalRent +
        bundle.totalMaintenance +
        bundle.totalEb +
        bundle.totalWater +
        bundle.totalAdvanceReceived;
    final income = bundle.transactions
        .where((t) => t.isIncome)
        .fold<double>(0, (sum, t) => sum + t.amount);
    return income - known;
  }
}

/// Excel workbook with Summary, By Property and Transactions sheets.
class ExcelReportExporter implements ReportExporter {
  const ExcelReportExporter();

  @override
  ExportFormat get format => ExportFormat.EXCEL;

  @override
  Future<Uint8List> build(ReportBundle bundle, {String? propertyName}) async {
    final excel = Excel.createExcel();
    final defaultSheet = excel.getDefaultSheet();

    _writeSummary(excel['Summary'], bundle);
    _writeProperties(excel['By Property'], bundle);
    _writeTransactions(excel['Transactions'], bundle);

    if (defaultSheet != null && defaultSheet != 'Summary') {
      excel.delete(defaultSheet);
    }

    final bytes = excel.encode() ?? <int>[];
    return Uint8List.fromList(bytes);
  }

  void _writeSummary(Sheet sheet, ReportBundle bundle) {
    sheet.appendRow([TextCellValue('RentLedger — Period Summary')]);
    sheet.appendRow([TextCellValue('Period'), TextCellValue(PdfBlocks.describeFilter(bundle, 'All properties'))]);
    sheet.appendRow([TextCellValue('Generated'), TextCellValue(Formatters.dateTime(bundle.generatedAt))]);
    sheet.appendRow([]);
    sheet.appendRow([TextCellValue('Metric'), TextCellValue('Amount')]);
    void row(String label, num value) => sheet.appendRow(
          [TextCellValue(label), DoubleCellValue(value.toDouble())],
        );
    row('Rent collected', bundle.totalRent);
    row('Maintenance collected', bundle.totalMaintenance);
    row('Electricity collected', bundle.totalEb);
    row('Water collected', bundle.totalWater);
    row('Total income', bundle.totalIncome);
    row('Total expenses', bundle.totalExpenses);
    row('Net operating income', bundle.netIncome);
    row('Advance received', bundle.totalAdvanceReceived);
    row('Advance refunded', bundle.totalAdvanceRefund);
    sheet.appendRow([
      TextCellValue('Units billed (EB)'),
      DoubleCellValue(bundle.totalUnitsBilled),
    ]);
    sheet.appendRow([
      TextCellValue('Entries'),
      IntCellValue(bundle.transactions.length),
    ]);
  }

  void _writeProperties(Sheet sheet, ReportBundle bundle) {
    sheet.appendRow([
      TextCellValue('Property'),
      TextCellValue('Income'),
      TextCellValue('Expense'),
      TextCellValue('Net'),
    ]);
    final income = <String, double>{};
    final expense = <String, double>{};
    for (final txn in bundle.transactions) {
      if (txn.isIncome) {
        income.update(txn.propertyId, (v) => v + txn.amount,
            ifAbsent: () => txn.amount);
      } else {
        expense.update(txn.propertyId, (v) => v + txn.amount,
            ifAbsent: () => txn.amount);
      }
    }
    for (final propertyId in {...income.keys, ...expense.keys}) {
      final earned = income[propertyId] ?? 0;
      final spent = expense[propertyId] ?? 0;
      sheet.appendRow([
        TextCellValue(bundle.propertyNameFor(propertyId)),
        DoubleCellValue(earned),
        DoubleCellValue(spent),
        DoubleCellValue(earned - spent),
      ]);
    }
  }

  void _writeTransactions(Sheet sheet, ReportBundle bundle) {
    sheet.appendRow([
      TextCellValue('Date'),
      TextCellValue('Property'),
      TextCellValue('Tenant'),
      TextCellValue('Type'),
      TextCellValue('Category'),
      TextCellValue('Method'),
      TextCellValue('Billing period'),
      TextCellValue('Units'),
      TextCellValue('Amount'),
      TextCellValue('Notes'),
    ]);
    for (final txn in bundle.transactions) {
      sheet.appendRow([
        TextCellValue(Formatters.dateTime(txn.recordedAt)),
        TextCellValue(bundle.propertyNameFor(txn.propertyId)),
        TextCellValue(txn.tenantName ?? ''),
        TextCellValue(txn.type.label),
        TextCellValue(txn.category.label),
        TextCellValue(txn.paymentMethod.label),
        TextCellValue(txn.billingPeriod),
        DoubleCellValue(txn.ebDetails?.unitsConsumed ?? 0),
        DoubleCellValue(txn.isExpense ? -txn.amount : txn.amount),
        TextCellValue(txn.notes ?? ''),
      ]);
    }
  }
}

/// Plain CSV for accountants who live in spreadsheets other than Excel.
class CsvReportExporter implements ReportExporter {
  const CsvReportExporter();

  @override
  ExportFormat get format => ExportFormat.CSV;

  @override
  Future<Uint8List> build(ReportBundle bundle, {String? propertyName}) async {
    final rows = <List<Object?>>[
      <Object?>[
        'Date',
        'Property ID',
        'Property',
        'Tenant ID',
        'Tenant',
        'Type',
        'Category',
        'Method',
        'Billing Period',
        'Units',
        'Unit Rate',
        'Amount',
        'Notes',
        'Transaction ID',
      ],
      ...bundle.transactions.map(
        (txn) => <Object?>[
          txn.recordedAt.toIso8601String(),
          txn.propertyId,
          bundle.propertyNameFor(txn.propertyId),
          txn.tenantId ?? '',
          txn.tenantName ?? '',
          txn.type.name,
          txn.category.name,
          txn.paymentMethod.name,
          txn.billingPeriod,
          txn.ebDetails?.unitsConsumed ?? '',
          txn.ebDetails?.unitRate ?? '',
          txn.isExpense ? -txn.amount : txn.amount,
          txn.notes ?? '',
          txn.transactionId,
        ],
      ),
    ];

    const converter = ListToCsvConverter();
    return Uint8List.fromList(utf8.encode(converter.convert(rows)));
  }
}

